/* Build: writes the installable loader, the bundle and an offline standalone copy.
   OWNER is the only placeholder; the version in package.json drives both @version and the
   pinned jsDelivr tag, so an update never serves stale modules from the CDN cache. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const OWNER = 'neokeeyyy';
const REPO = 'easytrac';
const BRANCH = 'main';
const VERSION = JSON.parse(readFileSync('package.json', 'utf8')).version;
const BASE = `https://cdn.jsdelivr.net/gh/${OWNER}/${REPO}@v${VERSION}/`;
const RAW = `https://raw.githubusercontent.com/${OWNER}/${REPO}/${BRANCH}/EasyTrac.user.js`;

const MODULES = [
  '01-core.js',
  '02-store.js',
  '03-http.js',
  '04-dates.js',
  '05-text.js',
  '06-permisos.js',
  '10-ui-tokens.js',
  '11-ui-sidebar.js',
  '12-ui-notice.js',
  '13-ui-grid.js',
  '14-ui-config.js',
  '20-acs.js',
  '30-acuses.js',
  '40-venta.js',
  '50-fecha.js',
  '70-traspasos.js',
];

const LIBS = [
  'https://cdnjs.cloudflare.com/ajax/libs/jspdf/2.5.1/jspdf.umd.min.js',
  'https://cdnjs.cloudflare.com/ajax/libs/jszip/3.10.1/jszip.min.js',
  'https://cdn.jsdelivr.net/npm/pdf-lib@1.17.1/dist/pdf-lib.min.js',
];

function header(requires) {
  return [
    '// ==UserScript==',
    '// @name         EasyTRAC',
    '// @namespace    easytrac',
    '// @version      ' + VERSION,
    '// @description  Toolkit SIRETRAC en un solo sidebar: ACS, acuses, venta, fecha y traspasos.',
    '// @author       ojuel',
    '// @match        https://siretrac.cne.gob.mx/*',
    '// @match        http://siretrac.cne.gob.mx/*',
    '// @grant        none',
    '// @run-at       document-idle',
    '// @noframes',
    '// @updateURL    ' + RAW,
    '// @downloadURL  ' + RAW,
    ...requires.map((u) => '// @require      ' + u),
    '// ==/UserScript==',
    '',
  ].join('\n');
}

const sources = MODULES.map((m) => ({
  name: m,
  /* The version lives in package.json alone: the running copy reports what was really built. */
  code: readFileSync('src/' + m, 'utf8').replace("ET.version = '0.0.0-dev';", "ET.version = '" + VERSION + "';"),
}));

const missing = sources.filter((s) => !s.code.includes('globalThis'));
if (missing.length) throw new Error('module without EasyTrac namespace: ' + missing.map((s) => s.name).join(', '));
if (sources.some((s) => s.code.includes('0.0.0-dev'))) throw new Error('version placeholder not replaced in 01-core.js');

const bundle = '/* EasyTRAC bundle: generated by tools/build.mjs. Do not edit. */\n' +
  sources.map((s) => '/* ---- src/' + s.name + ' ---- */\n' + s.code.trimEnd()).join('\n\n') + '\n';

mkdirSync('dist', { recursive: true });
writeFileSync('dist/easytrac.bundle.js', bundle, 'utf8');
/* The @require modules are published as-is, so the marker survives there: the loader body
   runs after them and is the only place that knows the installed version. */
writeFileSync('EasyTrac.user.js', header(LIBS.concat(MODULES.map((m) => BASE + 'src/' + m))) +
  "if (typeof EasyTrac !== 'undefined') EasyTrac.version = '" + VERSION + "';\n", 'utf8');
writeFileSync('dist/EasyTrac.standalone.user.js', header(LIBS) + bundle, 'utf8');

console.log('EasyTrac.user.js           v' + VERSION + ', ' + MODULES.length + ' @require (' + BASE + 'src/)');
console.log('dist/easytrac.bundle.js    ' + bundle.length + ' bytes');
console.log('dist/EasyTrac.standalone.user.js  offline build');
